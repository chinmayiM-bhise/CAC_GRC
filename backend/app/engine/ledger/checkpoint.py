"""
CAC-GRC External Ledger Integrity Checkpointing & Asymmetric Anchoring.

Threat Model & Cryptographic Guarantees:
----------------------------------------
1. Guarantees:
   - External Non-Repudiation: Binds the state of the sequential SHA-256 evidence ledger
     to an asymmetric cryptographic signature (Ed25519) generated by an authorized, dedicated signing key.
   - Truncation / Rollback Detection: Once a checkpoint is exported or anchored externally, an attacker
     cannot secretly roll back or truncate the ledger without violating the signed checkpoint sequence and hash.
   - Historical Integrity Locking: Verifies that every evidence record up to the checkpoint boundary
     preserves unbroken sequential linkage and canonical SHA-256 telemetry digests.
   - Deterministic Canonicalization: Uses strict key-sorted JSON serialization (separators=(',', ':'))
     to guarantee bit-for-bit reproducible digest calculations across independent platforms.

2. Honest Scope & Limitations:
   - Trust Boundary: Checkpointing proves that the signed sequence of records existed in that exact form
     at the time the private key signed the payload. It does NOT guarantee that the host OS clock was
     synchronized to an external atomic clock (no RFC 3161 TSA is implied).
   - Key Secrecy: Security of external verification depends entirely on the secrecy and isolation of
     the Ed25519 private key. Private keys must be stored in secure HSMs, separate filesystems, or
     restricted key vaults, never inside the application database or source repository.
   - Public Key Anchor: The verifier must independently trust the public key. An embedded public key in a
     checkpoint artifact cannot be self-authenticating; it must match a configured root of trust.
"""

import os
import json
import hashlib
import datetime
from dataclasses import dataclass, field
from typing import Optional, Dict, Any, Tuple, List, Union
from sqlalchemy.orm import Session
from cryptography.hazmat.primitives.asymmetric import ed25519
from cryptography.hazmat.primitives import serialization
from cryptography.exceptions import InvalidSignature

from app.models.evidence import EvidenceRecord
from app.models.base import utc_now
from app.engine.ledger.hasher import canonical_json_dump
from app.engine.ledger.vault import EvidenceVault
from app.engine.scoring.decay import ensure_utc

FORMAT_VERSION = "CAC-GRC-CHKPT-v1.0"
SIGNATURE_ALGORITHM = "Ed25519"
DEFAULT_LEDGER_ID = "CAC-GRC-PRIMARY-LEDGER"


# =============================================================================
# KEY MANAGEMENT PRIMITIVES
# =============================================================================

def generate_signing_keypair() -> Tuple[ed25519.Ed25519PrivateKey, ed25519.Ed25519PublicKey]:
    """Generates an RFC 8032 compliant Ed25519 keypair for ledger checkpoint signing."""
    private_key = ed25519.Ed25519PrivateKey.generate()
    public_key = private_key.public_key()
    return private_key, public_key


def serialize_private_key_pem(private_key: ed25519.Ed25519PrivateKey) -> str:
    """Serializes Ed25519 private key into PKCS#8 PEM format."""
    return private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption()
    ).decode("utf-8")


def serialize_public_key_pem(public_key: ed25519.Ed25519PublicKey) -> str:
    """Serializes Ed25519 public key into SubjectPublicKeyInfo (SPKI) PEM format."""
    return public_key.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo
    ).decode("utf-8")


def load_private_key_pem(pem_data: Union[str, bytes]) -> ed25519.Ed25519PrivateKey:
    """Loads an Ed25519 private key from PEM bytes or string."""
    if isinstance(pem_data, str):
        pem_data = pem_data.encode("utf-8")
    key = serialization.load_pem_private_key(pem_data, password=None)
    if not isinstance(key, ed25519.Ed25519PrivateKey):
        raise ValueError("Provided key is not an Ed25519 private key.")
    return key


def load_public_key_pem(pem_data: Union[str, bytes]) -> ed25519.Ed25519PublicKey:
    """Loads an Ed25519 public key from SPKI PEM bytes or string."""
    if isinstance(pem_data, str):
        pem_data = pem_data.encode("utf-8")
    key = serialization.load_pem_public_key(pem_data)
    if not isinstance(key, ed25519.Ed25519PublicKey):
        raise ValueError("Provided key is not an Ed25519 public key.")
    return key


def save_keypair(
    private_key: ed25519.Ed25519PrivateKey,
    public_key: ed25519.Ed25519PublicKey,
    private_path: str,
    public_path: str
) -> None:
    """Safely writes keypair to disk, ensuring directory existence."""
    os.makedirs(os.path.dirname(os.path.abspath(private_path)), exist_ok=True)
    os.makedirs(os.path.dirname(os.path.abspath(public_path)), exist_ok=True)

    with open(private_path, "w", encoding="utf-8") as f:
        f.write(serialize_private_key_pem(private_key))

    with open(public_path, "w", encoding="utf-8") as f:
        f.write(serialize_public_key_pem(public_key))


# =============================================================================
# CHECKPOINT PAYLOAD & DIGEST COMPUTATION
# =============================================================================

def build_canonical_checkpoint_payload(
    ledger_id: str,
    last_record_id: Optional[str],
    last_record_sequence: int,
    last_record_hash: str,
    timestamp: Optional[datetime.datetime] = None
) -> Dict[str, Any]:
    """
    Constructs the canonical dictionary representation of a ledger checkpoint.
    All keys are strictly specified for canonical serialization.
    """
    ts = ensure_utc(timestamp or utc_now()).isoformat()
    return {
        "checkpoint_timestamp": ts,
        "format_version": FORMAT_VERSION,
        "last_record_hash": last_record_hash,
        "last_record_id": last_record_id,
        "last_record_sequence": last_record_sequence,
        "ledger_id": ledger_id
    }


def compute_checkpoint_digest(payload: Dict[str, Any]) -> Tuple[str, bytes]:
    """
    Calculates SHA-256 over key-sorted canonical JSON bytes.
    Returns (hex_digest, canonical_bytes).
    """
    canonical_json = canonical_json_dump(payload)
    raw_bytes = canonical_json.encode("utf-8")
    digest = hashlib.sha256(raw_bytes).hexdigest()
    return digest, raw_bytes


# =============================================================================
# CHECKPOINT ISSUANCE (SIGNING)
# =============================================================================

def create_checkpoint(
    db: Session,
    private_key: ed25519.Ed25519PrivateKey,
    ledger_id: str = DEFAULT_LEDGER_ID,
    timestamp: Optional[datetime.datetime] = None
) -> Dict[str, Any]:
    """
    Inspects current database ledger state, builds canonical checkpoint payload,
    computes SHA-256 digest, and signs with Ed25519 private key.
    Uses strictly ordered records to guarantee unambiguous last-record selection.
    """
    latest_record = EvidenceVault.get_ordered_records(db, desc=True).first()
    record_count = db.query(EvidenceRecord).count()

    last_record_id = latest_record.id if latest_record else None
    last_record_hash = latest_record.payload_sha256 if latest_record else EvidenceVault.GENESIS_PREV_HASH

    payload = build_canonical_checkpoint_payload(
        ledger_id=ledger_id,
        last_record_id=last_record_id,
        last_record_sequence=record_count,
        last_record_hash=last_record_hash,
        timestamp=timestamp
    )

    digest, raw_bytes = compute_checkpoint_digest(payload)
    signature_bytes = private_key.sign(raw_bytes)
    public_pem = serialize_public_key_pem(private_key.public_key())

    return {
        "format_version": FORMAT_VERSION,
        "checkpoint_payload": payload,
        "checkpoint_sha256": digest,
        "signature": signature_bytes.hex(),
        "signature_algorithm": SIGNATURE_ALGORITHM,
        "public_key_pem": public_pem
    }


# =============================================================================
# CHECKPOINT VERIFICATION OPERATION
# =============================================================================

@dataclass
class CheckpointVerificationResult:
    is_valid: bool
    signature_valid: bool
    ledger_matched: bool
    status: str
    violations: List[str]
    checkpoint_summary: Dict[str, Any]


def verify_checkpoint(
    db: Session,
    checkpoint: Dict[str, Any],
    trusted_public_key: Optional[Union[ed25519.Ed25519PublicKey, str]] = None,
    min_expected_sequence: Optional[int] = None
) -> CheckpointVerificationResult:
    """
    Auditor-defensible verification operation:
    1. Validates structure, algorithm, and format version.
    2. Recalculates canonical SHA-256 digest over checkpoint_payload; rejects altered payloads.
    3. Resolves trusted public key (strictly requires trusted public key; NEVER trusts an embedded key blindly).
    4. Validates that embedded public key (if present) matches the trusted key.
    5. Cryptographically verifies Ed25519 signature against canonical payload bytes.
    6. Validates rollback resistance:
       - Detects if checkpoint sequence is older than min_expected_sequence.
       - Detects if local database contains fewer records than checkpoint asserts.
    7. Validates local ledger alignment:
       - Confirms referenced record exists and has matching hash.
       - Confirms unbroken sequential SHA-256 hash chain from genesis up to that checkpoint boundary.
       - Confirms sequence count alignment.
    """
    violations: List[str] = []

    # 1. Structural Validation
    if not isinstance(checkpoint, dict):
        return CheckpointVerificationResult(
            is_valid=False,
            signature_valid=False,
            ledger_matched=False,
            status="INVALID_STRUCTURE",
            violations=["Checkpoint artifact must be a valid JSON object / dictionary."],
            checkpoint_summary={}
        )

    payload = checkpoint.get("checkpoint_payload")
    claimed_digest = checkpoint.get("checkpoint_sha256")
    claimed_signature = checkpoint.get("signature")
    claimed_algorithm = checkpoint.get("signature_algorithm")
    format_version = checkpoint.get("format_version") or (payload.get("format_version") if isinstance(payload, dict) else None)

    if not isinstance(payload, dict) or not claimed_digest or not claimed_signature:
        return CheckpointVerificationResult(
            is_valid=False,
            signature_valid=False,
            ledger_matched=False,
            status="MALFORMED_CHECKPOINT",
            violations=["Checkpoint artifact is missing required fields (checkpoint_payload, checkpoint_sha256, signature)."],
            checkpoint_summary={}
        )

    # 2. Algorithm and Format Version Check
    if claimed_algorithm != SIGNATURE_ALGORITHM:
        violations.append(f"UNSUPPORTED_ALGORITHM: Signature algorithm '{claimed_algorithm}' is not supported (expected '{SIGNATURE_ALGORITHM}').")
        return CheckpointVerificationResult(
            is_valid=False,
            signature_valid=False,
            ledger_matched=False,
            status="UNSUPPORTED_ALGORITHM",
            violations=violations,
            checkpoint_summary=payload
        )

    if format_version != FORMAT_VERSION:
        violations.append(f"UNSUPPORTED_VERSION: Checkpoint version '{format_version}' is not supported (expected '{FORMAT_VERSION}').")
        return CheckpointVerificationResult(
            is_valid=False,
            signature_valid=False,
            ledger_matched=False,
            status="UNSUPPORTED_VERSION",
            violations=violations,
            checkpoint_summary=payload
        )

    # 3. Payload SHA-256 Digest Recalculation
    recalculated_digest, raw_bytes = compute_checkpoint_digest(payload)
    if recalculated_digest != claimed_digest:
        violations.append(
            f"PAYLOAD_TAMPERED: Recalculated checkpoint digest ({recalculated_digest}) does not match claimed digest ({claimed_digest})."
        )
        return CheckpointVerificationResult(
            is_valid=False,
            signature_valid=False,
            ledger_matched=False,
            status="PAYLOAD_TAMPERED",
            violations=violations,
            checkpoint_summary=payload
        )

    # 4. Resolve Trusted Public Key (NEVER blindly trust an embedded key from an untrusted artifact)
    public_key: Optional[ed25519.Ed25519PublicKey] = None
    if isinstance(trusted_public_key, ed25519.Ed25519PublicKey):
        public_key = trusted_public_key
    elif isinstance(trusted_public_key, str) and trusted_public_key.strip():
        try:
            public_key = load_public_key_pem(trusted_public_key)
        except Exception as e:
            violations.append(f"INVALID_KEY: Failed to parse provided trusted public key PEM: {str(e)}")
            return CheckpointVerificationResult(
                is_valid=False,
                signature_valid=False,
                ledger_matched=False,
                status="INVALID_KEY",
                violations=violations,
                checkpoint_summary=payload
            )
    else:
        # Check configured trusted public key path from settings
        from app.config import settings
        configured_path = getattr(settings, "LEDGER_VERIFY_KEY_PATH", None)
        if configured_path and os.path.exists(configured_path):
            try:
                with open(configured_path, "rb") as f:
                    public_key = load_public_key_pem(f.read())
            except Exception as e:
                violations.append(f"INVALID_KEY: Failed to load configured trusted public key from '{configured_path}': {str(e)}")
                return CheckpointVerificationResult(
                    is_valid=False,
                    signature_valid=False,
                    ledger_matched=False,
                    status="INVALID_KEY",
                    violations=violations,
                    checkpoint_summary=payload
                )

    if public_key is None:
        violations.append(
            "KEY_UNAVAILABLE: No trusted public key configured or provided. "
            "The verifier refuses to validate signatures against untrusted keys embedded solely within the unverified artifact."
        )
        return CheckpointVerificationResult(
            is_valid=False,
            signature_valid=False,
            ledger_matched=False,
            status="KEY_UNAVAILABLE",
            violations=violations,
            checkpoint_summary=payload
        )

    # Cross-check embedded public key if present in artifact
    if checkpoint.get("public_key_pem"):
        try:
            embedded_key = load_public_key_pem(checkpoint["public_key_pem"])
            trusted_bytes = serialize_public_key_pem(public_key)
            embedded_bytes = serialize_public_key_pem(embedded_key)
            if trusted_bytes != embedded_bytes:
                violations.append(
                    "UNTRUSTED_KEY: Embedded public key in checkpoint artifact does not match configured trusted public key anchor. "
                    "Possible key substitution or forgery attempt."
                )
                return CheckpointVerificationResult(
                    is_valid=False,
                    signature_valid=False,
                    ledger_matched=False,
                    status="UNTRUSTED_KEY",
                    violations=violations,
                    checkpoint_summary=payload
                )
        except Exception as e:
            violations.append(f"INVALID_KEY: Failed to parse embedded public key PEM: {str(e)}")
            return CheckpointVerificationResult(
                is_valid=False,
                signature_valid=False,
                ledger_matched=False,
                status="INVALID_KEY",
                violations=violations,
                checkpoint_summary=payload
            )

    # 5. Cryptographic Signature Verification
    signature_valid = False
    try:
        sig_bytes = bytes.fromhex(claimed_signature)
        public_key.verify(sig_bytes, raw_bytes)
        signature_valid = True
    except (InvalidSignature, ValueError) as e:
        violations.append(f"INVALID_SIGNATURE: Asymmetric cryptographic signature verification failed: {str(e)}")
        return CheckpointVerificationResult(
            is_valid=False,
            signature_valid=False,
            ledger_matched=False,
            status="INVALID_SIGNATURE",
            violations=violations,
            checkpoint_summary=payload
        )

    # 6. Rollback Resistance Checks
    last_record_id = payload.get("last_record_id")
    last_record_hash = payload.get("last_record_hash")
    last_record_seq = payload.get("last_record_sequence", 0)

    # External prior checkpoint sequence check
    if min_expected_sequence is not None and last_record_seq < min_expected_sequence:
        violations.append(
            f"ROLLBACK_DETECTED: Checkpoint sequence ({last_record_seq}) is older than minimum expected sequence ({min_expected_sequence}). Replay/rollback attempt detected."
        )
        return CheckpointVerificationResult(
            is_valid=False,
            signature_valid=signature_valid,
            ledger_matched=False,
            status="ROLLBACK_DETECTED",
            violations=violations,
            checkpoint_summary=payload
        )

    # Database rollback comparison: if local database has fewer records than checkpoint asserts
    total_in_db = db.query(EvidenceRecord).count()
    if total_in_db < last_record_seq:
        violations.append(
            f"ROLLBACK_DETECTED: Local database contains only {total_in_db} records, but trusted checkpoint asserts sequence {last_record_seq}. "
            f"Database has been truncated or rolled back to an earlier snapshot."
        )
        return CheckpointVerificationResult(
            is_valid=False,
            signature_valid=signature_valid,
            ledger_matched=False,
            status="ROLLBACK_DETECTED",
            violations=violations,
            checkpoint_summary=payload
        )

    # 7. Local Ledger Alignment & Continuity Verification
    ledger_matched = False

    # Sub-case: Empty Ledger Checkpoint
    if last_record_seq == 0 and last_record_id is None:
        if last_record_hash != EvidenceVault.GENESIS_PREV_HASH:
            violations.append(
                f"RECORD_HASH_MISMATCH: Empty ledger checkpoint expected genesis hash ({EvidenceVault.GENESIS_PREV_HASH}) but found ({last_record_hash})."
            )
        else:
            ledger_matched = True
            if total_in_db > 0:
                violations.append(f"NOTE: Validated historical empty-ledger checkpoint. Current ledger has progressed to {total_in_db} records.")

    # Sub-case: Checkpoint with records
    else:
        record = db.query(EvidenceRecord).filter_by(id=last_record_id).first()
        if not record:
            violations.append(
                f"RECORD_NOT_FOUND: Checkpoint references record '{last_record_id}' which does not exist in local database."
            )
        elif record.payload_sha256 != last_record_hash:
            violations.append(
                f"RECORD_HASH_MISMATCH: Checkpoint record hash ({last_record_hash}) does not match local record digest ({record.payload_sha256})."
            )
        else:
            # Verify unbroken hash chain from genesis up to this record boundary
            chain_ok, chain_violations = EvidenceVault.verify_ledger_integrity(db, up_to_record_id=last_record_id)
            if not chain_ok:
                violations.extend(chain_violations)
            else:
                # Count records strictly up to this record in insertion order
                ordered_recs = EvidenceVault.get_ordered_records(db, desc=False).all()
                count_up_to = 0
                for r in ordered_recs:
                    count_up_to += 1
                    if r.id == last_record_id:
                        break

                if count_up_to != last_record_seq:
                    violations.append(
                        f"SEQUENCE_MISMATCH: Checkpoint claimed sequence {last_record_seq} records, but local database contains {count_up_to} records up to '{last_record_id}'."
                    )
                else:
                    ledger_matched = True

    is_overall_valid = signature_valid and ledger_matched and len(violations) == 0

    status = "VERIFIED" if is_overall_valid else (
        "RECORD_NOT_FOUND" if any("RECORD_NOT_FOUND" in v for v in violations) else (
            "RECORD_HASH_MISMATCH" if any("RECORD_HASH_MISMATCH" in v for v in violations) else (
                "LEDGER_INTEGRITY_COMPROMISED" if any("TAMPER DETECTED" in v or "CHAIN LINKAGE" in v for v in violations) else (
                    "ROLLBACK_DETECTED" if any("ROLLBACK_DETECTED" in v for v in violations) else (
                        "SEQUENCE_MISMATCH" if any("SEQUENCE_MISMATCH" in v for v in violations) else "VERIFICATION_FAILED"
                    )
                )
            )
        )
    )

    return CheckpointVerificationResult(
        is_valid=is_overall_valid,
        signature_valid=signature_valid,
        ledger_matched=ledger_matched,
        status=status,
        violations=violations,
        checkpoint_summary=payload
    )


# =============================================================================
# EXPORT & IMPORT SERIALIZATION UTILITIES
# =============================================================================

def export_checkpoint_to_file(checkpoint: Dict[str, Any], filepath: str) -> str:
    """Exports signed checkpoint artifact to a JSON file."""
    os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(checkpoint, f, indent=2, sort_keys=True)
    return filepath


def load_checkpoint_from_file(filepath: str) -> Dict[str, Any]:
    """Loads a signed checkpoint artifact from a JSON file."""
    with open(filepath, "r", encoding="utf-8") as f:
        return json.load(f)
